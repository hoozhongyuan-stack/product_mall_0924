/** Actual Django/PostgreSQL CSRF/session writes; no HTTP mocks or external codes. */
import {test,expect} from '@playwright/test'
import {readFileSync,mkdirSync} from 'node:fs'
const access=JSON.parse(readFileSync(process.env.MALL_E2E_ACCESS_FILE!,'utf8'))
test.setTimeout(90_000)
test.use({actionTimeout:10_000})
test('real dining admin writes persist after reload and existing staff can be revoked',async({page},info)=>{
 await page.goto('/')
 await page.getByLabel('账号',{exact:true}).fill(access.account.loginName)
 await page.getByLabel('密码',{exact:true}).fill(access.account.password)
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await expect(page.getByRole('button',{name:'退出',exact:true})).toBeVisible()
 const unique=`餐饮联调_${info.project.name}_${Date.now()}`
 await page.goto('/dining-alliance/restaurants/new')
 await page.getByRole('textbox',{name:'餐饮店名称',exact:true}).fill(unique)
 await page.getByRole('textbox',{name:'联系人',exact:true}).fill('验收员')
 await page.getByRole('textbox',{name:'联系电话',exact:true}).fill('13800000000')
 await page.getByRole('textbox',{name:'店铺地址',exact:true}).fill('深圳隔离验收街2号')
 await page.getByRole('spinbutton',{name:'纬度',exact:true}).fill('22.5')
 await page.getByRole('spinbutton',{name:'经度',exact:true}).fill('114.1')
 await page.getByRole('button',{name:'保存餐饮店',exact:true}).click()
 await expect(page).toHaveURL(/\/dining-alliance\/restaurants\/[0-9a-f-]{36}$/)
 const id=new URL(page.url()).pathname.split('/').pop()!
 await expect(page.getByText(/餐饮联盟隔离前置仓/)).toBeVisible()
 await page.getByRole('button',{name:'批量新建',exact:true}).click()
 const tableDialog=page.getByRole('dialog',{name:'批量新建桌码',exact:true})
 await tableDialog.getByRole('textbox').last().fill('A01\nA02')
 await tableDialog.getByRole('button',{name:'校验并预览',exact:true}).click()
 await expect(tableDialog.getByText(/校验通过，共 2 张/)).toBeVisible()
 await tableDialog.getByRole('button',{name:'创建餐桌',exact:true}).click()
 await expect(tableDialog).not.toBeVisible()
 await expect(page.getByRole('cell',{name:'A01',exact:true})).toBeVisible()
 await expect(page.getByRole('cell',{name:'A02',exact:true})).toBeVisible()
 await page.getByRole('textbox',{name:'查找会员',exact:true}).fill('餐饮验收店长')
 await page.getByRole('button',{name:'查找会员',exact:true}).click()
 await page.getByRole('button',{name:'选择',exact:true}).click()
 await page.getByRole('button',{name:'保存授权',exact:true}).click()
 await expect(page.getByText('人员授权已保存。',{exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('textbox',{name:'餐饮店名称',exact:true})).toHaveValue(unique)
 await expect(page.getByText('A02',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'编辑授权',exact:true}).click()
 await expect(page.getByText(/已选择：餐饮验收店长/)).toBeVisible()
 await page.getByText('启用授权',{exact:true}).click()
 await expect(page.getByRole('checkbox',{name:'启用授权',exact:true})).not.toBeChecked()
 await page.getByRole('button',{name:'保存授权',exact:true}).click()
 await expect(page.getByText('人员授权已保存。',{exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByText('已停用',{exact:true})).toBeVisible()
 mkdirSync('test-results/browser',{recursive:true})
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:`test-results/browser/dining-alliance-real-detail-${info.project.name}.png`,fullPage:true})
 await page.goto('/dining-alliance/product-ratios')
 await page.getByRole('button',{name:'设置比例',exact:true}).first().click()
 const ratioDialog=page.getByRole('dialog',{name:'设置佣金比例',exact:true})
 await ratioDialog.getByRole('spinbutton').fill('20.25')
 await ratioDialog.getByRole('button',{name:'确认设置',exact:true}).click()
 await expect(page.getByText('商品佣金比例已保存，对所有餐饮店统一生效。',{exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('cell',{name:'20.25%',exact:true}).first()).toBeVisible()
 await page.getByRole('row').filter({has:page.getByRole('button',{name:'设置比例',exact:true})}).first().locator('.el-checkbox').click()
 await page.getByRole('button',{name:'批量设置佣金比例',exact:true}).click()
 // A one-item batch uses the same protected dialog as a single-row edit.
 await ratioDialog.getByRole('spinbutton').fill('20.50')
 await ratioDialog.getByRole('button',{name:'确认设置',exact:true}).click()
 await expect(ratioDialog).not.toBeVisible()
 await page.reload()
 await expect(page.getByRole('cell',{name:'20.5%',exact:true}).first()).toBeVisible()
 await page.screenshot({path:`test-results/browser/dining-alliance-batch-ratios-${info.project.name}.png`,fullPage:true})
 await page.goto('/dining-alliance')
 await expect(page.getByText(/前置仓筛选读取失败/)).toHaveCount(0)
 await page.getByRole('textbox',{name:'搜索餐饮店',exact:true}).fill(unique)
 await page.getByRole('button',{name:'查询',exact:true}).click()
 const restaurantRow=page.getByRole('row').filter({has:page.getByRole('link',{name:unique,exact:true})})
 await restaurantRow.locator('.el-checkbox').click()
 await page.getByRole('button',{name:'批量停用',exact:true}).click()
 await page.getByRole('button',{name:'确认继续',exact:true}).click()
 await expect(restaurantRow.getByRole('cell',{name:'停用',exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByText(/前置仓筛选读取失败/)).toHaveCount(0)
 await page.getByRole('textbox',{name:'搜索餐饮店',exact:true}).fill(unique)
 await page.getByRole('button',{name:'查询',exact:true}).click()
 await expect(restaurantRow.getByRole('cell',{name:'停用',exact:true})).toBeVisible()
 await restaurantRow.locator('.el-checkbox').click()
 await page.getByRole('button',{name:'批量启用',exact:true}).click()
 await page.getByRole('button',{name:'确认继续',exact:true}).click()
 await expect(restaurantRow.getByRole('cell',{name:'启用',exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByText(/前置仓筛选读取失败/)).toHaveCount(0)
 await page.getByRole('textbox',{name:'搜索餐饮店',exact:true}).fill(unique)
 await page.getByRole('button',{name:'查询',exact:true}).click()
 await expect(restaurantRow.getByRole('cell',{name:'启用',exact:true})).toBeVisible()
 await page.screenshot({path:`test-results/browser/dining-alliance-batch-stores-${info.project.name}.png`,fullPage:true})
 await page.goto('/dining-alliance/purchase-costs')
 await expect(page.getByRole('heading',{name:'历史餐饮进货价档案',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'保存覆盖',exact:true})).toHaveCount(0)
 await expect(page.getByRole('spinbutton')).toHaveCount(0)
 await page.goto('/orders/dining-alliance')
 await expect(page.getByRole('heading',{name:'餐饮联盟订单',exact:true})).toBeVisible()
 await expect(page.getByRole('combobox',{name:'履约前置仓',exact:true})).toBeVisible()
 await page.goto('/orders')
 await expect(page.getByRole('combobox',{name:'订单来源',exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'订单来源',exact:true}).selectOption('DINING')
 await page.getByRole('button',{name:'查询订单',exact:true}).click()
 await expect(page.getByText('当前条件下暂无订单。可调整筛选条件后查询。',{exact:true})).toBeVisible()
 const persisted=await page.request.get(`/api/v1/admin/dining-alliance/restaurants/${id}`)
 expect(persisted.status()).toBe(200)
 expect((await persisted.json()).data.name).toBe(unique)
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:`test-results/integration/dining-alliance-${info.project.name}.png`,fullPage:true})
})
